/// Согласие на запись разговора.
///
/// Зачем это существует: приложение слушает ЧУЖИЕ голоса. Человек должен знать, что он включает,
/// до первого нажатия, а не после. Правила здесь простые и проверяемые:
///   1. Без согласия запись не начинается вообще — не «предупреждение, которое можно пропустить».
///   2. Согласие фиксирует версию текста: если текст поменяли, согласие просят заново.
///   3. Приложение не обещает, что запись законна, — оно честно говорит, что решает человек.
class ConsentModel {
  ConsentModel({
    required this.version,
    required this.terms,
    this.acceptedVersion,
  });

  /// Версия текста согласия. Меняется при правке формулировок.
  final String version;

  /// Текст, который обязан быть виден человеку до старта.
  final List<String> terms;

  /// Версия, которую человек уже принял (или null, если никогда).
  final String? acceptedVersion;

  /// Можно ли начинать запись.
  bool get canRecord => acceptedVersion == version;

  /// Текст согласия поменяли — согласие нужно заново, старое не засчитывается.
  ConsentModel accept([String? version]) =>
      ConsentModel(version: this.version, terms: terms, acceptedVersion: version ?? this.version);

  /// Сброс: человек может отозвать согласие, и запись снова закрыта.
  ConsentModel revoke() => ConsentModel(version: version, terms: terms);

  /// Что показать, если запись попробовали начать без согласия.
  static const String blockMessage =
      'Перед записью нужно подтвердить, что вы понимаете: приложение слушает разговор и сохраняет его текст.';
}
