"""Начало сессии до того, как появилась запись.

Сначала найдено на живом примере, а не в теории: живому тексту нужен идентификатор сессии,
а идентификатор появлялся только при загрузке готового файла. То есть живой текст не мог
начаться никогда — либо ждать конца записи, что уже не «живой текст».

Поэтому сессия открывается заранее, пустой, и получает собственный идентификатор.
Файл записи появится позже, при остановке, и ляжет под тот же идентификатор.
"""

from __future__ import annotations

import secrets
from typing import Any

from .sessions import is_session_id


def new_session_id() -> str:
    """Случайный идентификатор: предсказуемый id позволил бы угадать чужую запись."""
    return secrets.token_hex(8)


def open_session() -> tuple[int, dict[str, Any]]:
    """Создаёт пустую сессию. Аудио появится отдельно, тем же идентификатором."""
    session_id = new_session_id()
    if not is_session_id(session_id):  # защита от собственной ошибки формата
        return 500, {"error": "internal", "message": "Не удалось создать идентификатор сессии."}
    return 200, {"session_id": session_id}
