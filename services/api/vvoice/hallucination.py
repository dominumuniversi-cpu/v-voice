"""Отсев известных фраз, которые распознавание придумывает в тишине и шуме.

Почему узкий список, а не «умный» фильтр: универсальная эвристика ошибается на живых фразах
и отрезает настоящую речь. Отрезать сказанное — непростительнее, чем оставить лишнюю строку.
Поэтому здесь только те фразы, которые микрофон не мог услышать: они не рождаются в разговоре.
Список открыт для дополнения — каждая новая фраза обязана быть сверена с реальным прогоном.
"""

from __future__ import annotations

# Фразы, которые ASR (Whisper, GigaAM, облачные модели) выдаёт в тишине, шуме и на музыке.
# Больше слов, чем в шаблоне + 1, — уже живая фраза, а не выдумка распознавания.
MAX_FILLER_WORDS = 7

_KNOWN_FILLERS = (
    "спасибо за просмотр",
    "спасибо за внимание",
    "продолжение следует",
    "субтитры сделал",
    "субтитры создавал",
    "субтитры подготовил",
    "подписывайтесь на канал",
    "ставьте лайки",
)


def _flat(text: str) -> str:
    """Единый вид для сравнения: нижний регистр, без ё и без хвостовой пунктуации."""
    cleaned = (text or "").lower().replace("ё", "е").strip()
    return cleaned.strip(" .,!?;:…—–-")


def is_hallucination(text: str) -> bool:
    """Фраза придумана распознаванием, а не произнесена человеком."""
    flat = _flat(text)
    if not flat:
        return False
    # Только короткая фраза целиком укладывается в известный шаблон. Живое «Спасибо за внимание,
    # коллеги, перейдём к смете» длиннее шаблона на много слов — это речь, и отрезать её нельзя.
    if len(flat.split()) > MAX_FILLER_WORDS:
        return False
    return any(flat.startswith(filler) for filler in _KNOWN_FILLERS)
